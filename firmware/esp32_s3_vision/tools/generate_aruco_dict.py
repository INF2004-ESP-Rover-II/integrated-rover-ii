"""Generate IDs 1..249 of DICT_6X6_250; preserve existing IDs/rotation encoding."""
from pathlib import Path
import re
import cv2
import numpy as np


def codes(marker_id):
    dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_6X6_250)
    image = cv2.aruco.generateImageMarker(dictionary, marker_id, 8)
    bits = image[1:-1, 1:-1] > 0
    result = []
    for rotation in range(4):
        value = 0
        for bit in np.rot90(bits, -rotation).flat:
            value = (value << 1) | int(bit)
        result.append(value)
    return result


if __name__ == '__main__':
    output = Path(__file__).resolve().parents[1] / 'main' / 'aruco_dict.h'
    # Refuse to silently change the meaning of IDs already used on the rover.
    existing = output.read_text(encoding='utf-8')
    for values, marker_id in re.findall(r'\{([^{}]+)\}, // ID (\d+)', existing):
        old = [int(value.strip().removesuffix('ULL'), 16) for value in values.split(',')]
        if old != codes(int(marker_id)):
            raise RuntimeError('Dictionary/rotation mismatch for existing ID ' + marker_id)
    lines = ['// Generated by tools/generate_aruco_dict.py from OpenCV DICT_6X6_250.',
             '#ifndef ARUCO_DICT_H', '#define ARUCO_DICT_H', '', '#include <stdint.h>', '',
             '#define ARUCO_FIRST_ID 1', '#define ARUCO_DICT_COUNT 249', '',
             '// Inner 6x6 bits, row-major, white=1; clockwise quarter-turn rotations.',
             'static const uint64_t ARUCO_DICT[ARUCO_DICT_COUNT][4] = {']
    for marker_id in range(1, 250):
        lines.append('    {' + ', '.join('0x%09XULL' % value for value in codes(marker_id)) + '}, // ID %d' % marker_id)
    lines += ['};', '', '#endif', '']
    output.write_text('\n'.join(lines), encoding='utf-8')
    print('Generated 249 IDs; verified every existing ID/rotation unchanged')
